def Postal_2():
    """Проверка возможности поступления абитуриента"""

    необходимые_экзамены = {
        "Информатика": 80,
        "Математика": 85,
        "Русский язык": 75 }

    print("""Для определения возможности поступления, необходима информация о Вас.

Для ввода экзамена и баллов введите их через |: Химия | 40.
Для завершения ввода нажмите Enter.
""")

    сданные_экзамены = {}

    try:
        while True:
            try:
                ввод = input(" ").strip()
                if ввод == " ":
                    break

                if "|" not in ввод: # Обработка ввода экзамена и балла
                    raise ValueError("Неверный формат. Используйте: Экзамен | Балл")

                части = ввод.split("|")
                if len(части) != 2:
                    raise ValueError("Неверный формат. Должно быть: Экзамен | Балл")

                экзамен, балл = [x.strip() for x in части]

                if not экзамен:
                    raise ValueError("Название экзамена не может быть пустым")

                try: # Проверка и преобразование балла
                    балл = int(балл)
                    if балл < 0 or балл > 100:
                        raise ValueError("Балл должен быть в диапазоне от 0 до 100")
                except ValueError:
                    raise ValueError("Балл должен быть целым числом")

                сданные_экзамены[экзамен] = балл

            except ValueError as err:
                print(f"Ошибка ввода: {err}.")
                continue # Пропускает текущую итерацию цикла и переходит к следующей

        print("\nВаши экзамены:") # Вывод введенных экзаменов
        if not сданные_экзамены:
            print("Нет введенных экзаменов")
        else:
            for i, (экзамен, балл) in enumerate(сданные_экзамены.items(), start = 1): # Нумерует элементы начиная с 1
                print("{} {} {}".format(i, экзамен, балл))

        # Проверка возможности поступления
        ok = True
        недостающие_экзамены = []
        низкие_баллы = []

        for необходимый_экзамен, необходимый_балл in необходимые_экзамены.items():
            if необходимый_экзамен not in сданные_экзамены:
                недостающие_экзамены.append(необходимый_экзамен)
                ok = False
            elif сданные_экзамены[необходимый_экзамен] < необходимый_балл:
                низкие_баллы.append(
                    f"{необходимый_экзамен} ({сданные_экзамены[необходимый_экзамен]} < {необходимый_балл})")
                ok = False

        # Вывод результата
        if ok:
            print("\nВы можете к нам поступить!")
        else:
            print("\nУвы...")
            if недостающие_экзамены:
                print(f"Не сданы необходимые экзамены: {', '.join(недостающие_экзамены)}")
            if низкие_баллы:
                print(f"Недостаточные баллы: {', '.join(низкие_баллы)}")

    except KeyboardInterrupt:
        print("\nПрограмма прервана пользователем")
    except Exception as err:
        print(f"\nНеизвестная ошибка: {err}")

if __name__ == "__main__": # Если файл запущен напрямую, то вызовет мою функцию
    Postal_2()